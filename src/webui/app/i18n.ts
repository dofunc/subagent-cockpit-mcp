const MESSAGES: Record<Lang, Record<MessageKey, string>> = { 'en': EN, 'zh-CN': ZH_CN, 'zh-TW': ZH_TW, 'ja': JA }

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string

/** Text for `key` in `lang`, with `{name}` placeholders filled from `vars`. */
export function translate(lang: Lang, key: MessageKey, vars: Record<string, string | number> = {}): string {
  return MESSAGES[lang][key].replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match))
}
